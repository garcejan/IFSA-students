def main() -> int:
    parser = argparse.ArgumentParser(
        description=(
            "Create the watsonx/ folder tree and wrapper scripts for a new "
            "graphql-wxo-agent-creator project. Safe to re-run — "
            "existing files are never overwritten unless --force is passed."
        ),
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    parser.add_argument(
        "--project-root",
        default=None,
        help="Project root directory (default: current working directory)",
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Print what would be created without writing anything",
    )
    parser.add_argument(
        "--force",
        action="store_true",
        help="Overwrite existing files (CAUTION: may overwrite agent.yaml)",
    )
    args = parser.parse_args()

    project_root = (
        Path(args.project_root).resolve()
        if args.project_root
        else Path.cwd()
    )

    scaffold(project_root, args.dry_run, args.force)
    return 0


if __name__ == "__main__":
    sys.exit(main())

