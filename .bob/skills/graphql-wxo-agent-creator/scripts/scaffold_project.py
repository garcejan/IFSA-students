# .env patching — append missing WXO vars (never overwrite existing values)
# ---------------------------------------------------------------------------

def _append_wxo_env_defaults(project_root: Path, dry_run: bool) -> None:
    """Append WXO_* default variables to .env if they are not already present.

    - Only appends lines whose key does not yet exist in the file.
    - Never modifies or removes existing lines.
    - If .env does not exist yet, skips silently (graphql-api-creator scaffold
      creates it; this function is safe to call in any order).
    """
    env_path = project_root / ".env"

    if not env_path.exists():
        print(f"  [SKIP] .env not found — WXO defaults will be added when .env is created: {env_path}")
        return

    try:
        existing = env_path.read_text(encoding="utf-8", errors="replace")
    except OSError as exc:
        print(f"  [WARN] Cannot read .env: {exc}", file=sys.stderr)
        return

    # Collect which WXO keys are already present (any non-comment occurrence)
    present_keys: set[str] = set()
    for line in existing.splitlines():
        stripped = line.strip()
        if stripped and not stripped.startswith("#") and "=" in stripped:
            key = stripped.split("=", 1)[0].strip()
            present_keys.add(key)

    # Build the lines to append (skip separator comment if all keys exist)
    lines_to_add: list[str] = []
    for line in _WXO_ENV_DEFAULTS.splitlines():
        stripped = line.strip()
        # Always carry header/comment/blank lines that introduce a new section
        if not stripped or stripped.startswith("#"):
            lines_to_add.append(line)
            continue
        if "=" not in stripped:
            lines_to_add.append(line)
            continue
        key = stripped.split("=", 1)[0].strip()
        if key in present_keys:
            print(f"  [SKIP] Already in .env: {key}")
        else:
            lines_to_add.append(line)

    # Drop trailing comment/blank lines that have no key lines after them
    while lines_to_add and (not lines_to_add[-1].strip() or
                             lines_to_add[-1].strip().startswith("#")):
        lines_to_add.pop()

    # Check if there is anything real to add
    real_lines = [l for l in lines_to_add
                  if l.strip() and not l.strip().startswith("#")]
    if not real_lines:
        print(f"  [SKIP] All WXO defaults already present in .env")
        return

    if dry_run:
        print(f"  [DRY-RUN] Would append {len(real_lines)} WXO variable(s) to: {env_path}")
        for l in real_lines:
            print(f"    + {l}")
        return

    try:
        # Ensure the file ends with a newline before appending
        suffix = "" if existing.endswith("\n") else "\n"
        with env_path.open("a", encoding="utf-8") as f:
            f.write(suffix + "\n".join(lines_to_add) + "\n")
        print(f"  [OK]   Appended {len(real_lines)} WXO variable(s) to: {env_path}")
        for l in real_lines:
            print(f"    + {l}")
    except OSError as exc:
        print(f"  [WARN] Cannot append to .env: {exc}", file=sys.stderr)


