def check_orchestrate_cli() -> list[str]:
    """Check that the orchestrate CLI is installed.

    Returns a list of warning strings if it is missing.
    Does NOT abort — callers print the warnings and continue.
    """
    warnings: list[str] = []
    found = shutil.which("orchestrate") is not None

    if found:
        try:
            proc = subprocess.run(
                ["orchestrate", "--version"],
                stdout=subprocess.PIPE, stderr=subprocess.PIPE,
                text=True, encoding="utf-8", errors="replace",
                timeout=10,
            )
            raw = (proc.stdout or proc.stderr or "").strip().splitlines()
            version = raw[0] if raw else "found"
        except Exception:
            version = "found"
        print(f"  ✅ orchestrate CLI: {version}")
    else:
        warnings.append(
            "orchestrate CLI not found — required to deploy the watsonx agent.\n"
            "    Install:  pip install ibm-watsonx-orchestrate\n"
            "    Docs:     https://www.ibm.com/docs/en/watsonx/watson-orchestrate/current"
            "?topic=cli-installing"
        )
        print("  ❌ orchestrate CLI: NOT FOUND  (pip install ibm-watsonx-orchestrate)")

    return warnings


