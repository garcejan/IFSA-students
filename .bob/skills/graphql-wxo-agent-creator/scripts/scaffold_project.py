# Main scaffold function
# ---------------------------------------------------------------------------

def scaffold(project_root: Path, dry_run: bool, force: bool) -> None:
    """Create the watsonx/ folder tree and helper files."""

    watsonx_dir = project_root / "watsonx"

    print(f"\nScaffolding watsonx agent project under: {project_root.resolve()}")
    if dry_run:
        print("Mode: DRY-RUN (no files will be written)\n")
    print()

    # ── watsonx/ directory ───────────────────────────────────────────────
    print("Directories:")
    _make_dir(watsonx_dir, dry_run)
    print()

    # ── Wrapper scripts inside watsonx/ ─────────────────────────────────
    print("Wrapper scripts (watsonx/):")
    _write_file(watsonx_dir / "deploy.py",   _DEPLOY_WRAPPER_TEMPLATE,   dry_run, force)
    _write_file(watsonx_dir / "undeploy.py", _UNDEPLOY_WRAPPER_TEMPLATE, dry_run, force)
    print()

    # ── agent.yaml stub (never overwrite a real one without --force) ─────
    print("Agent configuration stub:")
    _write_file(watsonx_dir / "agent.yaml", _AGENT_YAML_STUB, dry_run, force)
    print()

    # ── Append WXO defaults to .env (skip keys that already exist) ───────
    print("Environment defaults (.env):")
    _append_wxo_env_defaults(project_root, dry_run)
    print()

    # ── CLI prerequisite check ────────────────────────────────────────────
    if not dry_run:
        print("CLI prerequisites:")
        cli_warnings = check_orchestrate_cli()
        if cli_warnings:
            print()
            print("  ⚠  Install the missing CLI before running deploy/undeploy:")
            for w in cli_warnings:
                print(f"     • {w}")
        print()

    if dry_run:
        print("[DRY-RUN] No files were written. Remove --dry-run to apply.")
    else:
        print("[OK] Scaffolding complete.")
        print()
        print("Next steps:")
        print("  1. Review the WXO_* values appended to .env and adjust them for your project")
        print("  2. Load env vars:   python set-env.py | Invoke-Expression  (PowerShell)")
        print("                      source <(python3 set-env.py)           (bash/zsh)")
        print("  3. Generate schema: ask Bob to 'build the GraphQL API'")
        print("  4. Generate agent.yaml: ask Bob to 'create the agent YAML'")
        print("  5. Deploy: python watsonx/deploy.py")
        _print_readiness_summary(project_root)


