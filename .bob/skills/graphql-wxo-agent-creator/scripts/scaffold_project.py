def _print_readiness_summary(project_root: Path) -> None:
    """Print a structured readiness table after scaffolding completes."""
    watsonx_dir = project_root / "watsonx"
    graphql_dir = project_root / "api-connect" / "graphql"

    def status(path: Path, extra_check: str | None = None) -> str:
        if not path.exists():
            return "❌ missing"
        if extra_check:
            try:
                if extra_check in path.read_text(encoding="utf-8", errors="replace"):
                    return "⚠  needs editing"
            except OSError:
                pass
        return "✅ ready"

    print()
    print("=" * 62)
    print("  PROJECT READINESS — watsonx Orchestrate")
    print("=" * 62)
    print()
    print("  File / Resource                              Status")
    print("  " + "-" * 58)

    rows = [
        (".env",
         status(project_root / ".env", "your-environment-name-here")),
        ("set-env.py",
         status(project_root / "set-env.py")),
        ("watsonx/deploy.py (wrapper)",
         status(watsonx_dir / "deploy.py")),
        ("watsonx/undeploy.py (wrapper)",
         status(watsonx_dir / "undeploy.py")),
        ("watsonx/agent.yaml",
         status(watsonx_dir / "agent.yaml", "YOUR_AGENT_NAME_HERE")),
        ("api-connect/graphql/tools/*.graphql",
         "✅ ready" if any((graphql_dir / "tools").glob("*.graphql"))
         else "⚠  not generated yet"),
    ]

    for label, st in rows:
        print(f"  {label:<46} {st}")

    print()
    print("=" * 62)


